// Lightweight vi/en i18n for the chat UI (B5.4).
// Protocol labels (SCOPE_LABEL) and agent prompts stay in English by design.

export type UiLang = "en" | "vi";
export type LangPref = "auto" | UiLang;

export function resolveLang(pref?: LangPref, navLang?: string): UiLang {
  if (pref === "en" || pref === "vi") return pref;
  const raw = (navLang ?? (typeof navigator !== "undefined" ? navigator.language : "en")).toLowerCase();
  return raw.startsWith("vi") ? "vi" : "en";
}

